// Static build: src/ -> dist/, with the WeatherAPI key injected and versioned asset paths.
//
//   dist/index.html                      references the current release's files
//   dist/assets/<release>/css|js/...     CSS + JS, path unique per release
//
// <release> is a hash of the source files and key, so every change gets new URLs and a
// browser can never combine a fresh index.html with stale cached CSS/JS from an older release.
// Locally the key comes from .env; on Vercel it comes from the project's environment variables.
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = __dirname;
const src = path.join(root, 'src');
const out = path.join(root, 'dist');

function loadDotEnv() {
  const file = path.join(root, '.env');
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m || line.trim().startsWith('#')) continue;
    if (process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
}

function listFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? listFiles(p) : [p];
  }).sort();
}

loadDotEnv();
const key = (process.env.WEATHER_API_KEY || '').trim();
if (!key) {
  console.warn('[build] WEATHER_API_KEY is not set. The app will build but show an API configuration error.');
}

const configJs =
  '// Generated by build.js. Do not edit or commit.\n' +
  '// NOTE: this key ships to the browser. It is NOT a secret; restrict it in the WeatherAPI dashboard.\n' +
  `export const WEATHER_API_KEY = ${JSON.stringify(key)};\n`;

const hash = crypto.createHash('sha256');
for (const file of listFiles(src)) {
  hash.update(path.relative(src, file).replace(/\\/g, '/'));
  hash.update(fs.readFileSync(file));
}
hash.update(configJs);
const release = hash.digest('hex').slice(0, 10);
const assetDir = `assets/${release}`;

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, assetDir), { recursive: true });
fs.cpSync(path.join(src, 'css'), path.join(out, assetDir, 'css'), { recursive: true });
fs.cpSync(path.join(src, 'js'), path.join(out, assetDir, 'js'), { recursive: true });
fs.writeFileSync(path.join(out, assetDir, 'js', 'config.js'), configJs);

let html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
for (const ref of ['css/styles.css', 'js/app.js']) {
  if (!html.includes(`"${ref}"`)) throw new Error(`[build] index.html no longer references ${ref}`);
  html = html.replace(`"${ref}"`, `"${assetDir}/${ref}"`);
}
fs.writeFileSync(path.join(out, 'index.html'), html);

console.log(`[build] dist/ ready, release ${release} (${key ? 'API key injected' : 'no API key'})`);
